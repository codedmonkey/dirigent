<?php

declare(strict_types=1);

namespace CodedMonkey\Dirigent\Tests\FunctionalTests;

use CodedMonkey\Dirigent\Kernel;
use Symfony\Component\DependencyInjection\Loader\Configurator\ContainerConfigurator;
use Symfony\Component\Filesystem\Filesystem;

class TestKernel extends Kernel
{
    private readonly string $storagePath;

    public function __construct(string $environment, bool $debug)
    {
        $this->storagePath = sys_get_temp_dir() . '/' . uniqid('dirigent-storage-');

        parent::__construct($environment, $debug);
    }

    #[\Override]
    protected function configureContainer(ContainerConfigurator $container): void
    {
        parent::configureContainer($container);

        $container->extension('dirigent', [
            'storage' => [
                'path' => $this->storagePath,
            ],
        ]);
    }

    #[\Override]
    public function boot(): void
    {
        parent::boot();

        new Filesystem()->mkdir($this->storagePath);
    }

    #[\Override]
    public function shutdown(): void
    {
        new Filesystem()->remove($this->storagePath);

        parent::shutdown(); // TODO: Change the autogenerated stub
    }
}
